def build(p, chrome_head, chrome_tail, tpl):
    out = tpl
    for k in ('eyebrow', 'h1', 'hero_img', 'hero_alt', 'hero_pos', 'process_title', 'price_title', 'seo_title', 'key'):
        out = out.replace('{{' + k + '}}', p[k])
    out = out.replace('{{details}}', details_block(p))
    out = out.replace('{{works}}', works_block(p))
    out = out.replace('{{faq}}', faq_block(p))
    out = out.replace('{{also}}', also_block(p))
    out = out.replace('{{seo}}', ''.join(f'\n      <p>{t}</p>' for t in p['seo']))
    for k, v in ICON.items():
        out = out.replace('{{icon:' + k + '}}', svg(k))
    assert '{{' not in out, re.findall(r'\{\{[^}]+\}\}', out)

    head = chrome_head
    head = re.sub(r'<title>.*?</title>', f'<title>{p["title"]}</title>', head)
    head = re.sub(r'<meta name="description" content="[^"]*">', f'<meta name="description" content="{html.escape(p["description"])}">', head)
    head = head.replace('<link rel="stylesheet" href="assets/css/prices.css">',
                        '<link rel="stylesheet" href="assets/css/prices.css">\n'
                        '  <link rel="stylesheet" href="assets/css/works.css">\n'
                        '  <link rel="stylesheet" href="assets/css/clients.css">\n'
                        '  <link rel="stylesheet" href="assets/css/contacts.css">\n'
                        '  <link rel="stylesheet" href="assets/css/product.css">')
    tail = chrome_tail.replace(
        '  <!-- Прайс и форма — до main.js, чтобы новые блоки получили плавное появление -->\n'
        '  <script src="assets/js/prices-data.js"></script>\n'
        '  <script src="assets/js/prices.js"></script>\n',
        '  <!-- Прайс и детали — до main.js, чтобы новые блоки получили плавное появление -->\n'
        '  <script src="assets/js/prices-data.js"></script>\n'
        '  <script src="assets/js/prices.js"></script>\n'
        '  <script src="assets/js/product.js"></script>\n')
    assert 'product.js' in tail
    return head + out + tail


def main():
    src = io.open(os.path.join(ROOT, 'prices.html'), encoding='utf8').read()
    i = src.index('  <main class="page-prices">')
    j = src.index('  </main>') + len('  </main>\n')
    chrome_head, chrome_tail = src[:i], src[j:]
    tpl = io.open(os.path.join(ROOT, 'tools', 'men-page.html'), encoding='utf8').read()
    for p in PAGES:
        io.open(os.path.join(ROOT, p['file']), 'w', encoding='utf8', newline='\n').write(build(p, chrome_head, chrome_tail, tpl))
        print('ok', p['file'])


if __name__ == '__main__':
    main()
